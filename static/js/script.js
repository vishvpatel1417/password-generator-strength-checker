// 2. Secure Random Number Function

function secureRandomIndex(max) {

    if (!Number.isInteger(max) || max < 1 || max > 0x100000000) {
        throw new Error("Invalid random range");
    }

    const range = 0x100000000;
    const limit = range - (range % max);
    const array = new Uint32Array(1);

    let value;

    do {
        crypto.getRandomValues(array);
        value = array[0];
    } while (value >= limit);

    return value % max;
}


// 3. Secure Shuffle Function

function secureShuffle(array) {

    for (let i = array.length - 1; i > 0; i--) {

        const j = secureRandomIndex(i + 1);

        [array[i], array[j]] = [array[j], array[i]];

    }

    return array;
}


// 4. Generate Password Function
 
// Generate Password using Python Flask Backend

async function generatePassword() {

    const length = Number(lengthSlider.value);

    // Collect user options
    const passwordOptions = {
        length: length,
        uppercase: uppercase.checked,
        lowercase: lowercase.checked,
        numbers: numbers.checked,
        symbols: symbols.checked
    };

    // Check if at least one option is selected
    if (!Object.values(passwordOptions).slice(1).some(Boolean)) {
        alert("Please select at least one character option.");
        return;
    }

    try {

        generateBtn.disabled = true;
        generateBtn.textContent = "Generating...";

        // Send request to Python Flask
        const response = await fetch("/api/generate", {

            method: "POST",

            headers: {
                "Content-Type": "application/json"
            },

            body: JSON.stringify(passwordOptions)

        });

        // Receive Python response
        const result = await response.json();

        if (!response.ok) {
            throw new Error(result.error || "Generation failed");
        }

        // Display generated password
        generatedPassword.value = result.password;

        console.log("Password generated by Python:", result.length);

    } catch (error) {

        console.error("Error:", error);

        alert(error.message || "Unable to generate password.");

    } finally {

        generateBtn.disabled = false;
        generateBtn.textContent = "Generate Password";

    }

}


// Generate Button Event
generateBtn.addEventListener("click", generatePassword);



// 5. Copy Password Function

copyBtn.addEventListener("click", async function () {

    const password = generatedPassword.value;

    if (!password) {

        alert("Please generate a password first.");

        return;
    }

    try {

        await navigator.clipboard.writeText(password);

        copyBtn.textContent = "Copied!";

        setTimeout(() => {
            copyBtn.textContent = "Copy";
        }, 1500);

    } catch (error) {

        alert("Copy failed. Please copy the password manually.");

    }

});


// 6. Password Strength Checker

function checkStrength() {

    const password = checkPassword.value;

    if (!password) {

        strengthText.textContent = "Please enter a password.";

        strengthFill.style.width = "0%";

        suggestions.textContent = "";

        return;
    }

    let score = 0;

    const tips = [];

    // Check password length

    if (password.length >= 8) {
        score++;
    } else {
        tips.push("Use at least 8 characters.");
    }

    // Check uppercase

    if (/[A-Z]/.test(password)) {
        score++;
    } else {
        tips.push("Add uppercase letters.");
    }

    // Check lowercase

    if (/[a-z]/.test(password)) {
        score++;
    } else {
        tips.push("Add lowercase letters.");
    }

    // Check numbers

    if (/[0-9]/.test(password)) {
        score++;
    } else {
        tips.push("Add numbers.");
    }

    // Check special characters

    if (/[^A-Za-z0-9]/.test(password)) {
        score++;
    } else {
        tips.push("Add special characters.");
    }

    // Check common passwords

    const commonPasswords = [
        "password",
        "123456",
        "12345678",
        "qwerty",
        "admin",
        "password123"
    ];

    if (commonPasswords.includes(password.toLowerCase())) {

        score = 0;

        tips.unshift("Avoid common passwords.");

    } else {

        score++;

    }

    // Determine strength

    let strength = "";
    let percentage = 0;
    let color = "";

    if (score <= 1) {

        strength = "Weak";
        percentage = 20;
        color = "#ef4444";

    } else if (score <= 3) {

        strength = "Medium";
        percentage = 50;
        color = "#f59e0b";

    } else if (score <= 5) {

        strength = "Strong";
        percentage = 80;
        color = "#22c55e";

    } else {

        strength = "Very Strong";
        percentage = 100;
        color = "#00e5a0";

    }

    // Display result

    strengthText.textContent =
        "Password Strength: " + strength;

    strengthFill.style.width = percentage + "%";

    strengthFill.style.backgroundColor = color;

    // Display suggestions

    if (tips.length === 0) {

        suggestions.textContent =
            "Good! No basic improvements detected.";

    } else {

        suggestions.innerHTML =
            "<strong>Suggestions:</strong><br>" +
            tips.map(tip => "• " + tip).join("<br>");

    }

}


// Check Button Event

checkBtn.addEventListener("click", checkStrength);

